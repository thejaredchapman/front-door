const CATEGORY_RANK = { acutelyLow: 0, extremelyLow: 1, veryLow: 2, low: 3, moderate: 4, above: 5, any: 99 };

/** Programs a household could plausibly use, best matches first. */
export function matchPrograms({ categoryId, occupation, isFirstTimeBuyer, isVeteran }) {
  const userRank = CATEGORY_RANK[categoryId] ?? 5;
  return PROGRAMS
    .filter((p) => p.status !== 'closed')
    .filter((p) => (CATEGORY_RANK[p.maxCategory] ?? 99) >= userRank)
    .filter((p) => !p.veteranOnly || isVeteran)
    .filter((p) => !p.firstTime || isFirstTimeBuyer)
    .filter((p) => p.id !== 'section-184') // shown in directory; tribal membership not asked
    .filter((p) => p.occupations.includes('any') || p.occupations.includes(occupation))
    .map((p) => ({
      ...p,
      forYourJob: occupation !== 'any' && p.occupations.includes(occupation),
    }))
    .sort((a, b) => {
      const score = (p) => (p.forYourJob ? 0 : 10) + (p.status === 'verified' ? 0 : 3) + (p.type === 'counseling' ? -20 : 0) + (p.type === 'rebate' ? 8 : 0);
      return score(a) - score(b);
    });
}
